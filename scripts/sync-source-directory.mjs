function canonical(raw){
  try{
    const u=new URL(String(raw||'').trim());
    if(u.protocol!=='https:'||u.username||u.password||u.port&&u.port!=='443'||u.search||u.hash)return null;
    if(!u.hostname||u.hostname==='localhost'||u.hostname.endsWith('.local')||u.hostname.endsWith('.internal')||/^\d+\.\d+\.\d+\.\d+$/.test(u.hostname))return null;
    if(!/\/api\.php\/provide\/vod\/?$/i.test(u.pathname))return null;
    return (u.origin+u.pathname.replace(/\/+$/,'')).toLowerCase();
  }catch{return null}
}
function unpack(json){
  const records=json?.nodes?.[1]?.data;
  if(!Array.isArray(records))throw Error('directory schema changed: missing records');
  const deref=(i,depth=0)=>{if(!Number.isInteger(i)||i<0||i>=records.length||depth>16)return null;const v=records[i];if(Array.isArray(v))return v.map(x=>deref(x,depth+1));if(v&&typeof v==='object')return Object.fromEntries(Object.entries(v).map(([k,ref])=>[k,deref(ref,depth+1)]));return v};
  const root=deref(0);
  if(!Array.isArray(root?.onlineSources)||root.onlineSources.length<8)throw Error('directory schema changed: onlineSources');
  return root;
}
async function validate(api){
  try{
    const r=await fetch(api+'?ac=list',{signal:timeout(6500),headers:{accept:'application/json'}});
    if(!r.ok)return false;
    const t=await r.text();
    if(t.length>1_800_000)return false;
    const j=JSON.parse(t);
    return Array.isArray(j.class)&&j.class.length>0&&j.class.length<2000&&Array.isArray(j.list);
  }catch{return false}
}
async function main(){
  const r=await fetch(feedUrl,{signal:timeout(12000),headers:{accept:'application/json'}});
  if(!r.ok)throw Error('directory HTTP '+r.status);
  const ranks=unpack(await r.json());
  const online=ranks.onlineSources;
  const order=new Map();
  for(const [kind,field] of [['uptime','byUptime'],['resources','byResources'],['speed','bySpeed']]){
    for(const [index,item] of (ranks[field]||[]).entries()){
      const key=canonical(item?.api);if(!key)continue;
      if(!order.has(key))order.set(key,{});
      order.get(key)[kind]=index+1;
    }
  }
  const filtered=new Map(),excluded={invalid:0,adult:0,duplicated:0,unhealthy:0};
  for(const [index,item] of online.entries()){
    const url=canonical(item?.api), name=String(item?.name||'').trim().slice(0,65);
    if(!url||!name||item.status==='down'){excluded.invalid++;continue}
    if(adultNames.test(name)||adultHosts.has(new URL(url).hostname)){excluded.adult++;continue}
    if(filtered.has(url)){excluded.duplicated++;continue}
    filtered.set(url,{id:'auto_'+createHash('sha256').update(url).digest('hex').slice(0,14),name,api:url,kind:'auto',catalogRank:index+1,uptime:Number(item.uptime)||null,responseTime:Number(item.responseTime)||null,totalResources:Number(item.totalResources)||null,rank:order.get(url)||{}});
  }
  const entries=[...filtered.values()];
  let index=0,success=[];
  await Promise.all(Array.from({length:7},async()=>{while(index<entries.length){const e=entries[index++];if(await validate(e.api))success.push(e);else excluded.unhealthy++}}));
  const seen=new Set();
  success=success.filter(s=>{const k=canonical(s.api);if(seen.has(k))return false;seen.add(k);return true}).sort((a,b)=>a.catalogRank-b.catalogRank);
  let minimum=8;
  try{const old=JSON.parse(await fs.readFile(jsonFile,'utf8'));minimum=Math.max(minimum,Math.ceil((old?.entries?.length||0)*0.55));}catch{}
  if(success.length<minimum)throw Error('too few validated sources: '+success.length+' < '+minimum+'; preserving the last good snapshot');
  const payload={schema:1,upstream:feedUrl,generatedAt:new Date().toISOString(),sourceCount:success.length,entries:success};
  const json=JSON.stringify(payload,null,2)+'\n';
  const script='/* Generated by scripts/sync-source-directory.mjs. Do not edit manually. */\nwindow.LibreAutoSourcesData='+JSON.stringify(payload).replace(/</g,'\\u003c')+';\n';
  await fs.mkdir(path.dirname(jsonFile),{recursive:true});
  await fs.writeFile(jsonFile,json,'utf8');
  await fs.writeFile(outFile,script,'utf8');
  console.log('SYNC_RESULT',JSON.stringify({totalOnline:online.length,accepted:success.length,excluded,updated:payload.generatedAt}));
}
main().catch(e=>{console.error('SYNC_FAILED',e.message);process.exitCode=1});
